//postfix ve prefix farkları ve kullanımları

//örnek bir değişken
let number = 0; 

// Postfix: number++ (önce değeri kullan, sonra artır)
const result_postfix = number++;
console.log(result_postfix);

// Prefix: ++number (önce artır, sonra değeri kullan)
const result_prefix = ++number;
console.log(result_prefix);